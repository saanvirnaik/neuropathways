-- V3 (contact messages) is already deployed: preserve its version and checksum.
-- Create the practice schema before the existing V4-V8 question seeds.
CREATE TABLE practice_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill VARCHAR(50) NOT NULL,
    difficulty INTEGER NOT NULL,
    passage TEXT,
    question_text TEXT NOT NULL,
    optiona TEXT NOT NULL,
    optionb TEXT NOT NULL,
    optionc TEXT NOT NULL,
    correct_option VARCHAR(1) NOT NULL,
    explanation TEXT,
    active BOOLEAN NOT NULL,
    question_type VARCHAR(50) NOT NULL
);

CREATE TABLE practice_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    skill VARCHAR(50) NOT NULL,
    difficulty INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    current_question_number INTEGER NOT NULL,
    total_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL,
    started_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP
);

CREATE TABLE practice_session_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES practice_sessions(id),
    question_id BIGINT NOT NULL REFERENCES practice_questions(id),
    question_number INTEGER NOT NULL,
    CONSTRAINT uk_practice_session_position UNIQUE (session_id, question_number),
    CONSTRAINT uk_practice_session_question UNIQUE (session_id, question_id)
);

CREATE TABLE practice_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_question_id BIGINT NOT NULL REFERENCES practice_session_questions(id),
    selected_option VARCHAR(1) NOT NULL,
    correct BOOLEAN NOT NULL,
    response_time_ms BIGINT NOT NULL,
    used_read_aloud BOOLEAN NOT NULL,
    answered_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_practice_response_assignment UNIQUE (session_question_id)
);
