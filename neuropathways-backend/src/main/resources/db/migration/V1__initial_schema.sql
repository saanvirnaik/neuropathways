CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL CONSTRAINT uk_users_email UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE learner_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL CONSTRAINT uk_learner_preferences_user UNIQUE REFERENCES users(id),
    font_size INTEGER NOT NULL, font_family VARCHAR(255) NOT NULL,
    background_theme VARCHAR(255) NOT NULL, text_to_speech BOOLEAN NOT NULL,
    focus_mode BOOLEAN NOT NULL, reading_guide BOOLEAN NOT NULL,
    increased_spacing BOOLEAN NOT NULL, flexible_pace BOOLEAN NOT NULL
);
CREATE TABLE assessment_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill VARCHAR(50) NOT NULL, difficulty_level INTEGER NOT NULL,
    question_text VARCHAR(2000) NOT NULL, passage VARCHAR(4000),
    optiona VARCHAR(1000) NOT NULL, optionb VARCHAR(1000) NOT NULL,
    optionc VARCHAR(1000) NOT NULL, optiond VARCHAR(1000) NOT NULL,
    correct_option VARCHAR(1) NOT NULL, active BOOLEAN NOT NULL
);
CREATE TABLE assessment_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id), status VARCHAR(30) NOT NULL,
    current_question_number INTEGER NOT NULL, total_questions INTEGER NOT NULL,
    started_at TIMESTAMP NOT NULL, completed_at TIMESTAMP,
    overall_score INTEGER, calculated_level INTEGER
);
CREATE TABLE assessment_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES assessment_sessions(id),
    question_id BIGINT NOT NULL REFERENCES assessment_questions(id),
    selected_option VARCHAR(1) NOT NULL, correct BOOLEAN NOT NULL,
    attempt_number INTEGER NOT NULL, response_time_ms BIGINT,
    used_read_aloud BOOLEAN, submitted_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_response_session ON assessment_responses(session_id);
CREATE INDEX idx_response_question ON assessment_responses(question_id);
CREATE TABLE assessment_skill_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES assessment_sessions(id),
    skill VARCHAR(50) NOT NULL, total_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL, score_percent INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uk_session_skill UNIQUE (session_id, skill)
);
